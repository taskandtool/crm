#!/usr/bin/env node
// The proposal's stylesheet as code: compiles styles/proposal.css with
// Tailwind (classes from src/proposals), inlines each font it names from
// static/fonts/ as a data: URI, and writes src/proposals/style.ts, which
// every proposal page carries whole. Production has no files to read, so
// the CSS travels inside the code.
//
//   node scripts/proposal-css.mjs            # write it (npm run css runs this)
//   node scripts/proposal-css.mjs --check    # exit 1 when style.ts is not what the sources make
//   node scripts/proposal-css.mjs --watch    # write it again on every change (npm run dev)
import { spawnSync } from "node:child_process";
import { existsSync, mkdtempSync, readFileSync, rmSync, watch, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const OUT = "src/proposals/style.ts";
const USAGE = "usage: node scripts/proposal-css.mjs [--check | --watch]";
const args = process.argv.slice(2);
if (args.includes("--help") || args.includes("-h")) {
  console.log(`${USAGE}\n\nCompiles styles/proposal.css into ${OUT}, its fonts inlined.\nPrints "proposal css: written" or "proposal css: up to date". Exit 1 when\nthe compile fails, or with --check when ${OUT} is out of date; 2 when misused.`);
  process.exit(0);
}
if (args.some((a) => a !== "--check" && a !== "--watch")) {
  console.error(`proposal css: unknown ${args.join(" ")}\n  Try: ${USAGE}`);
  process.exit(2);
}

/** The module's text, or null with the reason printed. */
function compile() {
  const dir = mkdtempSync(join(tmpdir(), "proposal-css-"));
  try {
    const file = join(dir, "proposal.css");
    const r = spawnSync("node_modules/.bin/tailwindcss", ["-i", "styles/proposal.css", "-o", file, "--minify"], { encoding: "utf8" });
    if (r.status !== 0) {
      console.error(`proposal css: the compile failed\n${(r.stderr || "").trim().split("\n").slice(-6).join("\n")}\n  Try: fix styles/proposal.css, then npm run css`);
      return null;
    }
    let css = readFileSync(file, "utf8");
    const missing = [];
    css = css.replace(/url\((["']?)\/fonts\/([\w.-]+\.woff2)\1\)/g, (whole, _q, name) => {
      const path = join("static", "fonts", name);
      if (!existsSync(path)) {
        missing.push(path);
        return whole;
      }
      return `url(data:font/woff2;base64,${readFileSync(path).toString("base64")})`;
    });
    if (missing.length) {
      console.error(`proposal css: ${missing.join(", ")} not found\n  Try: put the WOFF2 file in static/fonts/, or remove its @font-face from styles/proposal.css`);
      return null;
    }
    return `// GENERATED by scripts/proposal-css.mjs from styles/proposal.css: change that, then npm run css.\nexport const PROPOSAL_CSS = ${JSON.stringify(css)};\n`;
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const current = () => (existsSync(OUT) ? readFileSync(OUT, "utf8") : "");

function write() {
  const text = compile();
  if (text === null) return false;
  if (text === current()) console.log("proposal css: up to date");
  else {
    writeFileSync(OUT, text);
    console.log(`proposal css: written to ${OUT}`);
  }
  return true;
}

if (args.includes("--check")) {
  const text = compile();
  if (text === null) process.exit(1);
  if (text !== current()) {
    console.error(`proposal css: ${OUT} is out of date with styles/proposal.css and src/proposals\n  Try: npm run css`);
    process.exit(1);
  }
  console.log("proposal css: up to date");
} else if (args.includes("--watch")) {
  write();
  let timer = null;
  const again = () => {
    clearTimeout(timer);
    timer = setTimeout(write, 150);
  };
  // style.ts is written by this script: a change to it is not a source change.
  watch("src/proposals", { recursive: true }, (_e, name) => name && !String(name).endsWith("style.ts") && again());
  watch("styles", (_e, name) => name === "proposal.css" && again());
  if (existsSync("static/fonts")) watch("static/fonts", again);
} else if (!write()) process.exit(1);
