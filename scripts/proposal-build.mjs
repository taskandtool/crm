#!/usr/bin/env node
// What a proposal page carries inside it, as code (production has no files
// to read):
//   src/proposals/style.ts   styles/proposal.css compiled by Tailwind, its
//                            fonts (static/fonts/*.woff2) inlined
//   src/proposals/photos.ts  every photograph a component names with
//                            photo("brand/images/…"), inlined as a data: URI
//
//   node scripts/proposal-build.mjs            # write both (npm run css runs this)
//   node scripts/proposal-build.mjs --check    # exit 1 when either is not what the sources make
//   node scripts/proposal-build.mjs --watch    # write them again on every change (npm run dev)
import { spawnSync } from "node:child_process";
import { existsSync, mkdtempSync, readdirSync, readFileSync, rmSync, statSync, watch, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { extname, join } from "node:path";

const STYLE = "src/proposals/style.ts";
const PHOTOS = "src/proposals/photos.ts";
const COMPONENTS = "src/proposals/components";
const MAX_PHOTO = 600 * 1024, MAX_ALL = 8 * 1024 * 1024;
const TYPES = { ".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".png": "image/png", ".webp": "image/webp", ".svg": "image/svg+xml" };
const USAGE = "usage: node scripts/proposal-build.mjs [--check | --watch]";
const args = process.argv.slice(2);
if (args.includes("--help") || args.includes("-h")) {
  console.log(`${USAGE}\n\nWrites ${STYLE} (styles/proposal.css compiled, fonts inlined) and ${PHOTOS}\n(every photo("…") in ${COMPONENTS}, inlined). Prints "proposal build: written" or\n"up to date". Exit 1 when a compile or a photo fails, or with --check when either\nfile is out of date; 2 when misused.`);
  process.exit(0);
}
if (args.some((a) => a !== "--check" && a !== "--watch")) {
  console.error(`proposal build: unknown ${args.join(" ")}; valid: --check, --watch\n  Try: node scripts/proposal-build.mjs --check`);
  process.exit(2);
}

/** style.ts's text, or null with the reason printed. */
function style() {
  const dir = mkdtempSync(join(tmpdir(), "proposal-css-"));
  try {
    const file = join(dir, "proposal.css");
    const r = spawnSync("node_modules/.bin/tailwindcss", ["-i", "styles/proposal.css", "-o", file, "--minify"], { encoding: "utf8" });
    if (r.error) {
      console.error(`proposal build: tailwindcss could not start (${r.error.message})\n  Try: npm install`);
      return null;
    }
    if (r.status !== 0) {
      console.error(`proposal build: the CSS did not compile\n${(r.stderr || "").trim().split("\n").slice(-6).join("\n")}\n  Try: fix styles/proposal.css, then npm run css`);
      return null;
    }
    const missing = [];
    const css = readFileSync(file, "utf8").replace(/url\((["']?)\/fonts\/([\w.-]+\.woff2)\1\)/g, (whole, _q, name) => {
      const path = join("static", "fonts", name);
      if (!existsSync(path)) return missing.push(path), whole;
      return `url(data:font/woff2;base64,${readFileSync(path).toString("base64")})`;
    });
    if (missing.length) {
      console.error(`proposal build: ${missing.join(", ")} not found\n  Try: put the WOFF2 file in static/fonts/, or remove its @font-face from styles/proposal.css`);
      return null;
    }
    return `// GENERATED by scripts/proposal-build.mjs from styles/proposal.css: change that, then npm run css.\nexport const PROPOSAL_CSS = ${JSON.stringify(css)};\n`;
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

/** photos.ts's text, or null with the reason printed. */
function photos() {
  const named = new Set();
  for (const f of readdirSync(COMPONENTS).filter((f) => f.endsWith(".tsx"))) {
    for (const m of readFileSync(join(COMPONENTS, f), "utf8").matchAll(/\bphoto\((["'`])([^"'`]+)\1\)/g)) named.add(m[2]);
  }
  const problems = [];
  const out = {};
  let total = 0;
  for (const path of [...named].sort()) {
    const type = TYPES[extname(path).toLowerCase()];
    if (!type) { problems.push(`${path}: a photograph is .jpg, .png, .webp or .svg`); continue; }
    if (!/^brand\/images\/[^/]+$/.test(path)) { problems.push(`${path}: a photograph is a file in brand/images/ (node scripts/proposal-photo.mjs <file> puts one there)`); continue; }
    if (!existsSync(path)) { problems.push(`${path}: not found (paths are from the app's folder; node scripts/proposal-photo.mjs <file> puts one in brand/images/)`); continue; }
    const size = statSync(path).size;
    if (size > MAX_PHOTO) { problems.push(`${path}: ${Math.ceil(size / 1024)} KB, over ${MAX_PHOTO / 1024} KB; node scripts/proposal-photo.mjs ${path} writes a smaller ${path.replace(/\.\w+$/, ".webp")}, which the component then names`); continue; }
    total += size;
    out[path] = `data:${type};base64,${readFileSync(path).toString("base64")}`;
  }
  if (total > MAX_ALL) problems.push(`the photographs come to ${(total / 1048576).toFixed(1)} MB, over ${MAX_ALL / 1048576} MB in one page; use fewer or smaller ones`);
  if (problems.length) {
    console.error(`proposal build: ${problems.length} photograph${problems.length === 1 ? "" : "s"} refused\n  - ${problems.join("\n  - ")}\n  Try: fix the photo("…") paths in ${COMPONENTS}, then npm run css`);
    return null;
  }
  return `// GENERATED by scripts/proposal-build.mjs from the photo("…") calls in ${COMPONENTS}: change those, then npm run css.\nexport const PHOTOS: Record<string, string> = ${JSON.stringify(out, null, 0)};\n`;
}

const current = (f) => (existsSync(f) ? readFileSync(f, "utf8") : "");
const build = () => {
  const s = style(), p = photos();
  return s === null || p === null ? null : [[STYLE, s], [PHOTOS, p]];
};

function write() {
  const files = build();
  if (!files) return false;
  const changed = files.filter(([f, text]) => text !== current(f));
  for (const [f, text] of changed) writeFileSync(f, text);
  console.log(changed.length ? `proposal build: written ${changed.map(([f]) => f).join(", ")}` : "proposal build: up to date");
  return true;
}

if (args.includes("--check")) {
  const files = build();
  if (!files) process.exit(1);
  const stale = files.filter(([f, text]) => text !== current(f)).map(([f]) => f);
  if (stale.length) {
    console.error(`proposal build: ${stale.join(", ")} out of date with styles/proposal.css and ${COMPONENTS}\n  Try: npm run css`);
    process.exit(1);
  }
  console.log("proposal build: up to date");
} else if (args.includes("--watch")) {
  write();
  let timer = null;
  const again = () => {
    clearTimeout(timer);
    timer = setTimeout(write, 150);
  };
  // The two files this writes live in src/proposals: a change to them is not a source change.
  watch("src/proposals", { recursive: true }, (_e, name) => name && !/(style|photos)\.ts$/.test(String(name)) && again());
  watch("styles", (_e, name) => name === "proposal.css" && again());
  for (const dir of ["static/fonts", "brand"]) if (existsSync(dir)) watch(dir, { recursive: true }, again);
} else if (!write()) process.exit(1);
